const DICTS: Record<Locale, Dict> = { zh: ZH, en: EN }
type TranslationKey = keyof typeof EN

type I18nContextValue = {
  locale: Locale
  setLocale: (next: Locale) => void
  localeTag: string
  t: (key: TranslationKey, params?: Params) => string
}

const I18nContext = createContext<I18nContextValue>({
  locale: 'en',
  setLocale: () => undefined,
  localeTag: 'en-US',
  t: (key, params) => interpolate(EN[key], params),
})

function interpolate(template: string, params?: Params): string {
  if (!params) return template
  return template.replace(/\{(\w+)\}/g, (_, k: string) => String(params[k] ?? `{${k}}`))
}

function resolveDefaultLocale(): Locale {
  const cached = localStorage.getItem('ui_locale')
  if (cached === 'zh' || cached === 'en') return cached
  const nav = navigator.language.toLowerCase()
  return nav.startsWith('zh') ? 'zh' : 'en'
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocale] = useState<Locale>(() => resolveDefaultLocale())
  useEffect(() => {
    localStorage.setItem('ui_locale', locale)
  }, [locale])

  const value = useMemo<I18nContextValue>(() => {
    const dict = DICTS[locale]
    return {
      locale,
      setLocale,
      localeTag: locale === 'zh' ? 'zh-CN' : 'en-US',
      t: (key, params) => interpolate(dict[key] ?? EN[key], params),
    }
  }, [locale])

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n() {
  return useContext(I18nContext)
}

