export function localizeErrorMessage(raw: string, t: I18nContextValue['t']): string {
  const normalized = raw.replace(/^Error:\s*/, '').trim()
  const lower = normalized.toLowerCase()
  if (lower.includes('unauthorized/invalid api key') || lower.includes('invalid api key')) {
    return t('error.invalid_api_key')
  }
  if (lower.includes('polyapiexception') && lower.includes('401')) {
    return t('error.invalid_api_key')
  }
  const key = ERROR_KEY_MAP[normalized]
  return key ? t(key) : normalized
}
